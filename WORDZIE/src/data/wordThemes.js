const themeStopWords = new Set(
    'a an the and or of to in for on with from as be being have has having ability able can could that this these those not no very more most less than then usually often especially also one person people thing something someone quality state act by its their they which who used use become make made does do at into off out up down it is are was were been like'.split(
        ' ',
    ),
);
const themeContextCache = new WeakMap();
const themeWordIndexCache = new WeakMap();
const themeWordsResultCache = new WeakMap();

const getContentWords = (value) =>
    (String(value || '').toLowerCase().match(/[a-z]+/g) || []).filter(
        (word) => word.length > 2 && !themeStopWords.has(word),
    );

const getThemeWordIndex = (wordDataByLetter) => {
    if (themeWordIndexCache.has(wordDataByLetter)) {
        return themeWordIndexCache.get(wordDataByLetter);
    }

    const allWords = Object.values(wordDataByLetter || {}).flat();
    const wordByKey = new Map();
    const tokensByWord = new WeakMap();

    for (const word of allWords) {
        const wordKey = word.word.trim().toLowerCase();
        if (!wordByKey.has(wordKey)) wordByKey.set(wordKey, word);
        tokensByWord.set(
            word,
            new Set([word.word, word.definition, ...(word.synonyms || [])].flatMap(getContentWords)),
        );
    }

    const index = { allWords, wordByKey, tokensByWord };
    themeWordIndexCache.set(wordDataByLetter, index);
    return index;
};

const getThemeContext = (wordDataByLetter) => {
    if (themeContextCache.has(wordDataByLetter)) {
        return themeContextCache.get(wordDataByLetter);
    }

    const { wordByKey } = getThemeWordIndex(wordDataByLetter);
    const tokensByTheme = new Map();
    const tokenFrequency = new Map();

    for (const theme of wordThemes) {
        const sourceWords = theme.words
            .map((word) => wordByKey.get(word.trim().toLowerCase()))
            .filter(Boolean);
        const tokens = new Set(
            [
                ...theme.words,
                ...(theme.keywords || []),
                ...sourceWords.flatMap((word) => [word.definition, ...(word.synonyms || [])]),
            ].flatMap(getContentWords),
        );
        tokensByTheme.set(theme.id, tokens);
        for (const token of tokens) tokenFrequency.set(token, (tokenFrequency.get(token) || 0) + 1);
    }

    const context = new Map(
        [...tokensByTheme].map(([themeId, tokens]) => [
            themeId,
            new Set([...tokens].filter((token) => tokenFrequency.get(token) <= 2)),
        ]),
    );
    themeContextCache.set(wordDataByLetter, context);
    return context;
};

export const getWordsForTheme = (theme, wordDataByLetter) => {
    let resultsByTheme = themeWordsResultCache.get(wordDataByLetter);
    if (!resultsByTheme) {
        resultsByTheme = new Map();
        themeWordsResultCache.set(wordDataByLetter, resultsByTheme);
    }
    if (resultsByTheme.has(theme.id)) return resultsByTheme.get(theme.id);

    const { allWords, wordByKey, tokensByWord } = getThemeWordIndex(wordDataByLetter);
    const themeKeys = new Set(theme.words.map((word) => word.trim().toLowerCase()));
    const themeSynonyms = new Set(
        [...themeKeys]
            .map((wordKey) => wordByKey.get(wordKey))
            .filter(Boolean)
            .flatMap((word) => word.synonyms || [])
            .map((synonym) => synonym.trim().toLowerCase()),
    );
    const relatedSynonyms = new Set(
        allWords
            .filter((word) => {
                const wordKey = word.word.trim().toLowerCase();
                return themeKeys.has(wordKey) || themeSynonyms.has(wordKey);
            })
            .flatMap((word) => word.synonyms || [])
            .map((synonym) => synonym.trim().toLowerCase()),
    );
    const themeContext = getThemeContext(wordDataByLetter).get(theme.id) || new Set();
    const directKeywords = new Set((theme.keywords || []).flatMap(getContentWords));
    const hasRelevantContext = (word) => {
        for (const token of tokensByWord.get(word) || []) {
            if (themeContext.has(token) || directKeywords.has(token)) return true;
        }
        return false;
    };

    const relatedWords = allWords.filter((word) => {
        const wordKey = word.word.trim().toLowerCase();
        return (
            themeKeys.has(wordKey) ||
            themeSynonyms.has(wordKey) ||
            relatedSynonyms.has(wordKey) ||
            hasRelevantContext(word) ||
            (word.synonyms || []).some((synonym) =>
                themeKeys.has(synonym.trim().toLowerCase()) ||
                themeSynonyms.has(synonym.trim().toLowerCase()),
            )
        );
    });
    resultsByTheme.set(theme.id, relatedWords);
    return relatedWords;
};
